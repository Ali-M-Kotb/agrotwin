"""Independent check of the water engine: modelled evapotranspiration vs NASA MODIS MOD16 ET.

For every cached site with MODIS NDVI (MOD13Q1), MODIS ET (MOD16A2GF) and NASA POWER weather: daily ET0 (FAO-56
Penman–Monteith, POWER) × a crop coefficient read from the field's own NDVI (Kc = 1.25·NDVI − 0.10), with the FAO-56
bucket for rain-fed sites, summed over each 8-day MOD16 composite. MOD16 is an independent NASA product (different
physics: Penman–Monteith with MODIS LAI/albedo and MERRA-2 forcing), so agreement is evidence, not circularity.
    python qa/et_validation.py   → qa/ET_VALIDATION.md, qa/ET_VALIDATION.json
"""
import json
import sys
from pathlib import Path

import numpy as np
import pandas as pd

ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(ROOT / "backend"))
import data_sources as ds  # noqa: E402
import pulse  # noqa: E402

RAINFED = {(31.28, 27.35), (31.449, 27.065), (33.9, -5.45), (28.832, 28.798)}

def site_rows():
    seen, out = [], []
    for f in sorted((ROOT / "data" / "cache").glob("modis_MOD16A2GF_*.json")):
        lat, lon = map(float, f.stem.split("_")[-2:])
        if any(abs(lat - a) < 0.02 and abs(lon - b) < 0.02 for a, b in seen):
            continue
        try:
            et = ds.modis_et(lat, lon, offline=True).dropna()
            nd = ds.modis_ndvi(lat, lon, offline=True).dropna()
            w, elev = ds.power_daily(lat, lon, offline=True)
        except Exception:
            continue
        if len(et) < 40 or len(nd) < 40:
            continue
        seen.append((lat, lon))
        w = ds.add_et0(w, lat, elev)
        kc = (pulse.KC_A * nd + pulse.KC_B).clip(0.15, 1.2).resample("D").interpolate()
        rainfed = any(abs(lat - a) < 0.2 and abs(lon - b) < 0.2 for a, b in RAINFED)
        if rainfed:
            eta = pulse._bucket(w, kc)["etc"] * pulse._bucket(w, kc)["ks"]
        else:
            eta = kc.reindex(w.index).ffill().bfill() * w["ET0"]
        rows = []
        for d, v in et.items():
            seg = eta.loc[d:d + pd.Timedelta(days=7)]
            if len(seg) == 8 and np.isfinite(seg).all():
                rows.append((d, float(seg.sum()), float(v)))
        if len(rows) < 30:
            continue
        df = pd.DataFrame(rows, columns=["date", "model", "mod16"]).set_index("date")
        mon = df.resample("MS").sum()
        out.append(dict(lat=lat, lon=lon, rainfed=rainfed, n=len(df), r_8day=float(df.corr().iloc[0, 1]),
                        r_monthly=float(mon.corr().iloc[0, 1]), ratio_model_to_mod16=float(df.model.sum() / max(df.mod16.sum(), 1e-6)),
                        annual_model_mm=float(df.model.mean() * 365 / 8), annual_mod16_mm=float(df.mod16.mean() * 365 / 8)))
    return out

def main():
    rows = site_rows()
    irr = [r for r in rows if not r["rainfed"]]
    rf = [r for r in rows if r["rainfed"]]
    agg = lambda rs, k: float(np.median([r[k] for r in rs])) if rs else None
    rep = dict(sites=rows, irrigated=dict(n=len(irr), median_r_monthly=agg(irr, "r_monthly"), median_ratio=agg(irr, "ratio_model_to_mod16")),
               rainfed=dict(n=len(rf), median_r_monthly=agg(rf, "r_monthly"), median_ratio=agg(rf, "ratio_model_to_mod16")))
    (ROOT / "qa" / "ET_VALIDATION.json").write_text(json.dumps(rep, indent=1))
    L = ["# Water engine vs NASA MODIS MOD16 evapotranspiration (independent check)", "",
         "_Generated by `python qa/et_validation.py`. script written with AI coding assistance and reviewed by the team._", "",
         "| site | type | 8-day composites | r (8-day) | r (monthly) | model / MOD16 | annual model mm | annual MOD16 mm |", "|---|---|---|---|---|---|---|---|"]
    for r in rows:
        L.append(f"| {r['lat']:.2f}, {r['lon']:.2f} | {'rain-fed' if r['rainfed'] else 'irrigated'} | {r['n']} | {r['r_8day']:.2f} | {r['r_monthly']:.2f} | {r['ratio_model_to_mod16']:.2f} | {r['annual_model_mm']:.0f} | {r['annual_mod16_mm']:.0f} |")
    L += ["", f"Irrigated sites (n = {len(irr)}): median monthly r = {rep['irrigated']['median_r_monthly']:.2f}, median model/MOD16 = {rep['irrigated']['median_ratio']:.2f}." if irr else "",
          f"Rain-fed sites (n = {len(rf)}): median monthly r = {rep['rainfed']['median_r_monthly']:.2f}, median model/MOD16 = {rep['rainfed']['median_ratio']:.2f}." if rf else "", "",
          "Reading: the seasonal timing agrees (correlation); the level differs because MOD16 is a 500 m pixel average that is known to "
          "underestimate ET over irrigated cropland in arid regions, while the model assumes a fully irrigated crop. The level gap is "
          "reported, not tuned away."]
    (ROOT / "qa" / "ET_VALIDATION.md").write_text("\n".join(L) + "\n")
    print("\n".join(L))

if __name__ == "__main__":
    main()
