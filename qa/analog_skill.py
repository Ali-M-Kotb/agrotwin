"""Does the pre-season state (NASA POWER, Aug–Sep) tell us which past years the coming season resembles?

AI-generated (Claude, Anthropic) under human review — see docs/AI_USE.md.
For each year y (leave-one-out), past years are weighted by similarity of their Aug–Sep Tmax anomaly and root-zone
wetness (GWETROOT) anomaly to year y's; the weighted ensemble of their coming-season outcomes is scored against y's
actual outcome (CRPS), versus equal weights. Outcomes: winter (Nov–Apr) reference ET and rain, summer (May–Sep) ET.
If the weighting does not beat equal weights, AgroTwin keeps equal weights (and says so).
    python qa/analog_skill.py   → qa/ANALOG.md, qa/ANALOG.json
"""
import json
import sys
from pathlib import Path

import numpy as np
import pandas as pd

ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(ROOT / "backend"))
import data_sources as ds  # noqa: E402

SITES = {"delta_01": (31.25, 30.95), "coast_01": (31.28, 27.35), "intl_01": (33.9, -5.45)}


def crps(x, w, y):
    x, w = np.asarray(x, float), np.asarray(w, float) / np.sum(w)
    t1 = np.sum(w * np.abs(x - y))
    t2 = 0.5 * np.sum(w[:, None] * w[None, :] * np.abs(x[:, None] - x[None, :]))
    return t1 - t2


def table(lat, lon):
    w, elev = ds.power_daily(lat, lon, offline=True)
    w = ds.add_et0(w, lat, elev)
    rows = []
    for y in range(1991, w.index[-1].year):
        pre = w.loc[f"{y}-08-01":f"{y}-09-30"]
        win = w.loc[f"{y}-11-01":f"{y + 1}-04-30"]
        sm = w.loc[f"{y + 1}-05-01":f"{y + 1}-09-30"]
        if len(pre) < 55 or len(win) < 170 or len(sm) < 140:
            continue
        rows.append(dict(year=y, tmax=pre["T2M_MAX"].mean(), gwet=pre["GWETROOT"].mean(), rain_pre=pre["PRECTOTCORR"].sum(),
                         win_et0=win["ET0"].sum(), win_rain=win["PRECTOTCORR"].sum(), sum_et0=sm["ET0"].sum()))
    t = pd.DataFrame(rows).set_index("year")
    t["trend"] = np.polyval(np.polyfit(t.index, t["tmax"], 1), t.index)
    t["tmax_a"] = t["tmax"] - t["trend"]                       # detrended, so warming itself is not the signal
    return t


def evaluate(t, bw):
    z = (t[["tmax_a", "gwet"]] - t[["tmax_a", "gwet"]].mean()) / t[["tmax_a", "gwet"]].std()
    out = {}
    for target in ("win_et0", "win_rain", "sum_et0"):
        # detrend targets too (the replay already warms past years)
        yv = t[target] - np.polyval(np.polyfit(t.index, t[target], 1), t.index)
        s_eq, s_w = [], []
        for y in t.index:
            others = t.index != y
            d2 = ((z[others] - z.loc[y]) ** 2).sum(1).values
            wts = np.exp(-0.5 * d2 / bw ** 2)
            s_eq.append(crps(yv[others].values, np.ones(others.sum()), yv.loc[y]))
            s_w.append(crps(yv[others].values, wts, yv.loc[y]))
        out[target] = dict(crps_equal=float(np.mean(s_eq)), crps_weighted=float(np.mean(s_w)), skill=float(1 - np.mean(s_w) / np.mean(s_eq)), n=len(t))
    return out


def main():
    res = {}
    for sid, (lat, lon) in SITES.items():
        t = table(lat, lon)
        res[sid] = {f"bw={bw}": evaluate(t, bw) for bw in (0.75, 1.0, 1.5)}
    best = {s: max(v.items(), key=lambda kv: np.mean([x["skill"] for x in kv[1].values()])) for s, v in res.items()}
    mean_skill = float(np.mean([np.mean([x["skill"] for x in b[1].values()]) for b in best.values()]))
    verdict = "adopt" if mean_skill > 0.05 else "keep equal weights"
    rep = dict(results=res, best=best, mean_skill=mean_skill, verdict=verdict,
               method="leave-one-year-out, Gaussian kernel on standardised detrended Aug–Sep Tmax anomaly and GWETROOT, CRPS vs equal weights; note the bandwidth was chosen on the same years (optimistic)")
    (ROOT / "qa" / "ANALOG.json").write_text(json.dumps(rep, indent=1, default=str))
    L = ["# Season-ahead analog weighting: does the pre-season state help?", "",
         "_Generated by `python qa/analog_skill.py`. AI-written script (Claude), human review._", "",
         "Skill = 1 − CRPS(weighted) / CRPS(equal weights); above 0 means the pre-season state helps. Detrended targets.", "",
         "| site | bandwidth | winter ET0 | winter rain | summer ET0 |", "|---|---|---|---|---|"]
    for s, v in res.items():
        for bw, r in v.items():
            L.append(f"| {s} | {bw} | {r['win_et0']['skill']:+.0%} | {r['win_rain']['skill']:+.0%} | {r['sum_et0']['skill']:+.0%} |")
    L += ["", f"Mean skill at each site's best bandwidth: **{mean_skill:+.1%}** → **{verdict}**.", "",
          "Bandwidths are compared on the same years, so the best value is slightly optimistic."]
    (ROOT / "qa" / "ANALOG.md").write_text("\n".join(L) + "\n")
    print("\n".join(L))


if __name__ == "__main__":
    main()
